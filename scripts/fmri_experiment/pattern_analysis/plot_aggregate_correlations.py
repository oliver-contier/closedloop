#!/usr/bin/env python
"""
Script to plot aggregated fMRI pattern correlation results across multiple subjects.

Loads selectivity indices (simple, contrast, separability, distinctiveness)
generated by run_pattern_correlation.py for a list of subjects and creates
separate bar plots for each index, showing the mean value per condition across
subjects. Individual subject data points are overlaid using a stripplot.
"""

import argparse
import logging
from pathlib import Path
from typing import List, Optional
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from matplotlib.lines import Line2D

# Configure logging
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

def build_filename_suffix(
    statstype: str,
    similarity_metric: str,
    split_method: str,
    fisher_z: bool,
    zscore_voxels: bool,
    bootstrap: bool,
    n_bootstrap: int,
    permutation: bool,
    n_permutations: int,
    shuffle_split: Optional[str] = None,  # Add this parameter
    denoising_approach: str = 'compcor',  # Add this parameter
    reliability_threshold: float = 0.3,
) -> str:
    """
    Reconstructs the suffix part of the filenames generated by run_pattern_correlation.py
    based on the analysis parameters, including bootstrap or permutation info.

    Args:
        statstype: Type of statistic ('betas' or 'contrasts').
        similarity_metric: Similarity metric used ('pearson', 'spearman', 'euclidean_distance', etc.).
        split_method: Split method ('crosssplit' or 'samesplit').
        fisher_z: Whether Fisher Z-transform was used (relevant for correlations).
        zscore_voxels: Whether voxel z-scoring was applied.
        bootstrap: Whether bootstrapping was used.
        n_bootstrap: Number of bootstrap iterations (if bootstrap=True).
        permutation: Whether permutation testing was used.
        n_permutations: Number of permutation iterations (if permutation=True).
        shuffle_split: Which split was shuffled for permutation ('odd', 'even', or None for both).
        denoising_approach: Denoising approach used ('motion', 'compcor', 'aroma').

    Returns:
        The constructed filename suffix string (excluding subject and specific metric).
    """
    is_correlation = similarity_metric in ['pearson', 'spearman']
    z_transform_str = "_fisherz" if fisher_z and is_correlation else ""
    zscore_str = "_voxzscored" if zscore_voxels else ""
    rel_suffix = ""
    if reliability_threshold is not None and reliability_threshold > 0.0:
        rel_suffix = f"_relthr-{reliability_threshold:.2f}"
    test_suffix = ""
    if bootstrap:
        test_suffix = f"_bootstrap{n_bootstrap}"
    elif permutation:
        shuffle_suffix = f"_shuffle{shuffle_split}" if shuffle_split else "_shuffleboth"
        test_suffix = f"_permtest{n_permutations}{shuffle_suffix}"

    # Use metric-{metric} format and add test suffix, reliability suffix, and denoising approach
    suffix = (f"stat-{statstype}_metric-{similarity_metric}_{split_method}"
              f"{z_transform_str}{zscore_str}{test_suffix}{rel_suffix}_denoised-{denoising_approach}")
    return suffix

def load_condition_labels(results_root: Path, first_subject: str) -> List[str]:
    """
    Loads condition labels from the specified subject's directory.
    Assumes labels are consistent across subjects.

    Args:
        results_root: Path to the main results directory containing subject folders.
        first_subject: ID of the subject whose label file to load.

    Returns:
        A list of condition label strings.

    Raises:
        FileNotFoundError: If the label file cannot be found.
        Exception: If there is an error reading the label file.
    """
    label_file = results_root / f'sub-{first_subject}' / f'sub-{first_subject}_condition_labels.txt'
    if not label_file.exists():
        raise FileNotFoundError(f"Condition label file not found: {label_file}")
    try:
        # Use ndmin=1 for robustness if there's only one label
        labels = np.loadtxt(label_file, dtype=str, ndmin=1).tolist()
        # Handle case where loadtxt might return a single string if file has one line
        if isinstance(labels, str):
            labels = [labels]
        return labels
    except Exception as e:
        logger.error(f"Error loading condition labels from {label_file}: {e}")
        raise

def load_all_subject_data(
    results_root: Path,
    subjects: List[str],
    metric_key: str,
    filename_suffix: str,
    condition_labels: List[str]
) -> pd.DataFrame:
    """
    Loads the specified metric data, significance data (bootstrap), CI data (bootstrap),
    and p-value data (permutation) for all subjects and combines them into a pandas DataFrame.

    Args:
        results_root: Path to the main results directory.
        subjects: List of subject IDs.
        metric_key: The internal key name of the metric (e.g., 'simple_selectivity').
        filename_suffix: The common suffix part (e.g., 'stat-contrasts..._permtest1000').
        condition_labels: The list of condition labels.

    Returns:
        A pandas DataFrame with columns 'Subject', 'Condition', the metric_key,
        'Significant' (bool, from bootstrap), 'ci_lower', 'ci_upper', and
        'p_value' (float, from permutation). Columns will contain defaults (False/NaN)
        if corresponding files are missing.

    Raises:
        ValueError: If no metric data could be loaded successfully for any subject.
    """
    all_data = []
    n_conditions = len(condition_labels)

    for sub in subjects:
        subj_dir = results_root / f'sub-{sub}'
        # Construct filename for the main metric data (uses the specific metric_key)
        metric_filename = f"sub-{sub}_{filename_suffix}_{metric_key}.npy"

        # Special handling for base metric filenames
        if metric_key == 'within_corrs':
            metric_filename = f"sub-{sub}_{filename_suffix}_within_metrics.npy"
        elif metric_key == 'mean_between_corrs':
            metric_filename = f"sub-{sub}_{filename_suffix}_mean_between_metrics.npy"
        elif metric_key == 'pairwise_corrs':
            metric_filename = f"sub-{sub}_{filename_suffix}_pairwise_metrics.npy"

        metric_file = subj_dir / metric_filename

        # Construct paths for significance (bootstrap), CI (bootstrap), and p-value (permutation) files
        significance_filename = f"sub-{sub}_{filename_suffix}_{metric_key}_significant_gt_0.npy"
        ci_lower_filename = f"sub-{sub}_{filename_suffix}_{metric_key}_ci_lower.npy"
        ci_upper_filename = f"sub-{sub}_{filename_suffix}_{metric_key}_ci_upper.npy"
        pvalue_filename = f"sub-{sub}_{filename_suffix}_{metric_key}_pvalue.npy"

        # Update paths based on potential base metric adjustments
        if metric_key == 'pairwise_corrs': # Pairwise likely doesn't have significance/pvalue files
             significance_filename = None
             pvalue_filename = None
             # CI filenames might exist if bootstrap was run
             ci_lower_filename = f"sub-{sub}_{filename_suffix}_pairwise_metrics_ci_lower.npy"
             ci_upper_filename = f"sub-{sub}_{filename_suffix}_pairwise_metrics_ci_upper.npy"
        # Reset paths to Path objects or None
        significance_file = subj_dir / significance_filename if significance_filename else None
        ci_lower_file = subj_dir / ci_lower_filename if ci_lower_filename else None
        ci_upper_file = subj_dir / ci_upper_filename if ci_upper_filename else None
        pvalue_file = subj_dir / pvalue_filename if pvalue_filename else None

        if not metric_file.exists():
            logger.warning(f"Metric file not found for subject {sub}, key '{metric_key}': {metric_file}. Skipping subject for this metric.")
            continue

        try:
            metric_data = np.load(metric_file)
            if metric_data.ndim == 0: metric_data = np.array([metric_data.item()])
            if metric_key == 'pairwise_corrs': continue # Skip loading 2D pairwise
            if len(metric_data) != n_conditions: # Check length for 1D metrics
                logger.warning(f"Data length mismatch for subject {sub}, key '{metric_key}': expected {n_conditions} conditions, found {len(metric_data)} in {metric_file}. Skipping.")
                continue

            subject_df = pd.DataFrame({
                'Subject': f'sub-{sub}',
                'Condition': condition_labels,
                metric_key: metric_data
            })

            # --- Load Optional Significance/CI/P-value Data --- #

            # Bootstrap Significance (Lower CI > 0)
            sig_loaded = False
            if significance_file and significance_file.exists():
                try:
                    significance_data = np.load(significance_file)
                    if significance_data.ndim == 0: significance_data = np.array([significance_data.item()])
                    if len(significance_data) == n_conditions:
                        subject_df['Significant'] = significance_data.astype(bool)
                        sig_loaded = True
                    else:
                        logger.warning(f"Bootstrap significance length mismatch for sub {sub}, key '{metric_key}'. Setting Significant to False.")
                except Exception as e:
                    logger.error(f"Error loading bootstrap significance for sub {sub}, key '{metric_key}': {e}. Setting Significant to False.")
            if not sig_loaded:
                subject_df['Significant'] = False # Default if file missing or error

            # Bootstrap CIs
            ci_loaded = False
            if ci_lower_file and ci_upper_file and ci_lower_file.exists() and ci_upper_file.exists():
                try:
                    ci_lower_data = np.load(ci_lower_file)
                    ci_upper_data = np.load(ci_upper_file)
                    if ci_lower_data.ndim == 0: ci_lower_data = np.array([ci_lower_data.item()])
                    if ci_upper_data.ndim == 0: ci_upper_data = np.array([ci_upper_data.item()])
                    if len(ci_lower_data) == n_conditions and len(ci_upper_data) == n_conditions:
                        subject_df['ci_lower'] = ci_lower_data
                        subject_df['ci_upper'] = ci_upper_data
                        ci_loaded = True
                    else:
                        logger.warning(f"CI data length mismatch for sub {sub}, key '{metric_key}'. Setting CIs to NaN.")
                except Exception as e:
                    logger.error(f"Error loading CI data for sub {sub}, key '{metric_key}': {e}. Setting CIs to NaN.")
            if not ci_loaded:
                subject_df['ci_lower'] = np.nan # Default
                subject_df['ci_upper'] = np.nan # Default

            # Permutation P-values
            pval_loaded = False
            if pvalue_file and pvalue_file.exists():
                try:
                    pvalue_data = np.load(pvalue_file)
                    if pvalue_data.ndim == 0: pvalue_data = np.array([pvalue_data.item()])
                    if len(pvalue_data) == n_conditions:
                        subject_df['p_value'] = pvalue_data
                        pval_loaded = True
                    else:
                        logger.warning(f"P-value data length mismatch for sub {sub}, key '{metric_key}'. Setting p_value to NaN.")
                except Exception as e:
                    logger.error(f"Error loading p-value data for sub {sub}, key '{metric_key}': {e}. Setting p_value to NaN.")
            if not pval_loaded:
                subject_df['p_value'] = np.nan # Default

            # --- End Loading Optional Data --- #

            all_data.append(subject_df)
        except Exception as e:
            logger.error(f"Error loading/processing data for subject {sub}, key '{metric_key}' from {metric_file}: {e}")
            continue

    if not all_data:
        raise ValueError(f"No data loaded successfully for metric key '{metric_key}'. Check file paths and parameters.")

    return pd.concat(all_data, ignore_index=True)

def plot_aggregated_metric(
    data: pd.DataFrame,
    metric: str,
    output_dir: Path,
    plot_filename_base: str,
    metric_ylabel: str = None,
    subjects: List[str] = None,
    alpha_level: float = 0.05
) -> None:
    """
    Creates and saves a bar plot of the aggregated metric.
    Shows group mean bars with standard 95% CI, overlaid individual points
    (highlighted based on significance), and counts of significant subjects
    at the bottom.

    Args:
        data: DataFrame containing combined subject data.
        metric: Name of the metric being plotted.
        output_dir: Directory to save the plot.
        plot_filename_base: Base filename for the output plot.
        metric_ylabel: Label for the y-axis.
        subjects: List of subject IDs for consistent color mapping.
        alpha_level: Significance threshold for highlighting and counting.
    """
    if metric_ylabel is None:
        metric_ylabel = metric.replace('_', ' ').title()

    n_subjects = len(subjects) if subjects else data['Subject'].nunique()
    palette = sns.color_palette("tab10", n_colors=max(n_subjects, 10))
    subject_ids = sorted(data['Subject'].unique()) if subjects is None else [f'sub-{s}' for s in sorted(subjects)]
    color_map = {sub: palette[i % len(palette)] for i, sub in enumerate(subject_ids)}

    # Determine significance source and calculate significance for sorting
    large_size = 10
    small_size = 6
    plot_jitter = True
    has_perm_pvals = 'p_value' in data.columns and data['p_value'].notna().any()
    has_boot_sig = 'Significant' in data.columns and data['Significant'].notna().any()
    significance_source = None
    if has_perm_pvals:
        significance_source = 'permutation'
        logger.info(f"Highlighting points based on permutation p-values (p < {alpha_level}).")
    elif has_boot_sig:
        significance_source = 'bootstrap'
        logger.info(f"Highlighting points based on bootstrap significance (lower CI > 0).")
    else:
        logger.warning("No significance data found. Plotting all points with small size.")

    # Keep track of which points are significant for sorting and counting
    data['_is_significant_'] = False # Add temporary column

    # Determine significance for each data point
    for subj_id in subject_ids:
        subject_data = data[data['Subject'] == subj_id]
        subj_indices = subject_data.index # Get indices for updating the main df

        if significance_source == 'permutation':
            sig_mask = subject_data['p_value'] < alpha_level
            positive_metric_mask = subject_data[metric] > 0
            combined_sig_mask = sig_mask & positive_metric_mask
            data.loc[subj_indices, '_is_significant_'] = combined_sig_mask
        elif significance_source == 'bootstrap':
            sig_mask = subject_data['Significant']
            data.loc[subj_indices, '_is_significant_'] = sig_mask

    # Sort conditions by number of significant subjects (descending), then by mean value
    if significance_source:
        significance_counts = data.groupby('Condition')['_is_significant_'].sum()
        # For conditions with same significance count, sort by mean value
        mean_values = data.groupby('Condition')[metric].mean()
        # Create a combined sorting key: (-sig_count, -mean_value)
        combined_sort = pd.DataFrame({
            'sig_count': significance_counts,
            'mean_value': mean_values
        }).fillna(0)
        combined_sort = combined_sort.sort_values(['sig_count', 'mean_value'], ascending=[False, False])
        sorted_conditions = combined_sort.index.tolist()
        logger.info(f"Sorted conditions by significance count: {dict(significance_counts[sorted_conditions])}")
    else:
        # Fallback to mean value sorting if no significance data
        mean_metric_series = data.groupby('Condition')[metric].mean()
        sorted_conditions = mean_metric_series.sort_values(ascending=False).index.tolist()
        logger.info("No significance data available. Sorted conditions by mean value.")

    fig, ax = plt.subplots(figsize=(14, 6.5))
    adjust_right_boundary = 0.85
    plot_title = f"Aggregated {metric_ylabel} ({metric}) - Group Means & Individual Points"

    # 1. Plot bars without confidence intervals
    sns.barplot(
        data=data,
        x='Condition',
        y=metric,
        order=sorted_conditions,
        color='skyblue',
        edgecolor='black',
        errorbar=None,
        ax=ax
    )

    # 2. Overlay Stripplot - Highlighting individual significance

    for subj_id in subject_ids:
        subject_data = data[data['Subject'] == subj_id]
        subject_color = color_map[subj_id]
        
        # Use the already determined significance from the temporary column
        sig_mask = subject_data['_is_significant_']
        data_sig = subject_data[sig_mask]
        data_nonsig = subject_data[~sig_mask]

        # Plot significant points (large)
        if not data_sig.empty:
            sns.stripplot(data=data_sig, x='Condition', y=metric, order=sorted_conditions, color=subject_color, jitter=plot_jitter, size=large_size, label='_nolegend_', dodge=False, ax=ax, alpha=1.)
        # Plot non-significant points (small)
        if not data_nonsig.empty:
            sns.stripplot(data=data_nonsig, x='Condition', y=metric, order=sorted_conditions, color=subject_color, jitter=plot_jitter, size=small_size, label='_nolegend_', dodge=False, ax=ax, alpha=1.)

    # 3. Add Significance Counts Annotation at the bottom
    counts_added = False
    if significance_source: # Only add counts if significance info exists
        ymin, ymax = ax.get_ylim()
        y_pos = ymin + (ymax - ymin) * 0.02 # Position near bottom
        for i, condition in enumerate(sorted_conditions):
            # Use the temporary column to count significant subjects
            count = data[(data['Condition'] == condition) & data['_is_significant_']]['Subject'].nunique()
            ax.text(i, y_pos, str(count), ha='center', va='bottom', fontsize=9, color='black', fontweight='bold')
        counts_added = True
        # Adjust lower ylim slightly ONLY if counts were actually added
        ax.set_ylim(bottom = ymin - (ymax - ymin) * 0.05)

    # Clean up temporary column
    if '_is_significant_' in data.columns:
         del data['_is_significant_']

    # 4. Add Subject Legend
    legend_elements = [Line2D([0], [0], marker='o', color='w', label=subj_id, markersize=8, markerfacecolor=color_map[subj_id]) for subj_id in subject_ids]
    ax.legend(handles=legend_elements, title="Subjects", bbox_to_anchor=(1.05, 1), loc='upper left')

    # --- Common Plot Adjustments ---
    plt.ylabel(metric_ylabel)
    plt.title(plot_title)
    plt.xticks(rotation=60, ha='right', fontsize=10)
    plt.yticks(fontsize=10)
    plt.axhline(0, color='grey', linestyle='--', linewidth=0.8)
    plt.tight_layout(rect=[0, 0, adjust_right_boundary, 1])

    output_file = output_dir / plot_filename_base
    plt.savefig(output_file, dpi=300, bbox_inches='tight')
    logger.info(f"Plot saved to {output_file}")
    plt.close()

def main():
    parser = argparse.ArgumentParser(
        description="Plot aggregated pattern similarity/dissimilarity indices across subjects.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter
    )
    parser.add_argument("--results_root", type=str, required=True, help="Path to the root directory containing subject pattern analysis results.")
    parser.add_argument("--output_dir", type=str, required=True, help="Directory to save the output plots.")
    parser.add_argument("--subjects", nargs='+', required=True, help="List of subject IDs to include.")
    parser.add_argument("--statstype", type=str, default='contrasts', choices=['betas', 'contrasts'], help="Statistic type used.")
    parser.add_argument("--similarity-metric", type=str, default='euclidean_distance', choices=['pearson', 'spearman', 'euclidean_distance', 'euclidean_inverse', 'euclidean_rbf'], help="Similarity/dissimilarity metric used.")
    parser.add_argument("--split-method", type=str, default='crosssplit', choices=['crosssplit', 'samesplit'], help="Split method used.")
    parser.add_argument("--raw-values", dest='fisher_z', action='store_false', default=True, help="Flag if raw values were used (disables Fisher-Z assumption for correlations).")
    parser.add_argument("--zscore-voxels", action='store_true', default=True, help="Voxel z-scoring was applied (default: True).")
    parser.add_argument("--no-zscore-voxels", dest='zscore_voxels', action='store_false', help="Disable assumption that voxel z-scoring was applied.")
    parser.add_argument("--denoising-approach", type=str, default='compcor', choices=['motion', 'compcor', 'aroma'], help="Denoising approach used.")

    # --- Mutually Exclusive Group for Bootstrap/Permutation --- #
    stat_test_group = parser.add_mutually_exclusive_group()
    stat_test_group.add_argument("--bootstrap", action='store_true', default=False, help="Load bootstrap results (CIs, significance).")
    stat_test_group.add_argument("--permutation", action='store_true', default=False, help="Load permutation results (p-values).")

    # --- Arguments for Bootstrap/Permutation (affect filename suffix) --- #
    parser.add_argument("--n-bootstrap", type=int, default=1000, help="Number of bootstrap iterations used.")
    parser.add_argument("--confidence-level", type=float, default=0.95, help="Confidence level for bootstrap intervals (only affects loading).",)
    parser.add_argument("--n-permutations", type=int, default=1000, help="Number of permutation iterations used.")
    parser.add_argument("--shuffle-split", type=str, choices=['odd', 'even', None], default=None, help="Which split was shuffled for permutation testing.")

    # --- Other arguments ---
    parser.add_argument("--plot_suffix", type=str, default="", help="Optional suffix string to add to the output plot filename.")
    parser.add_argument("--save_format", type=str, default='pdf', choices=['png', 'pdf'], help="Output file format.")
    parser.add_argument("--alpha", type=float, default=0.05, help="Significance level for p-value highlights/counts on plots.")
    parser.add_argument(
        "--reliability-threshold",
        type=float,
        default=0.3,
        help="Voxel reliability threshold (r) that was used in the subject-level analysis. "
             "Must match the value passed to run_pattern_correlation.py."
    )

    args = parser.parse_args()

    results_root = Path(args.results_root).resolve()
    output_dir = Path(args.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    try:
        # Build the common suffix part of the filenames
        filename_suffix = build_filename_suffix(
            args.statstype, args.similarity_metric, args.split_method,
            args.fisher_z, args.zscore_voxels,
            args.bootstrap, args.n_bootstrap,
            args.permutation, args.n_permutations,
            args.shuffle_split, args.denoising_approach,
            args.reliability_threshold,
        )
        logger.info(f"Attempting to load files with suffix part: {filename_suffix}")

        condition_labels = load_condition_labels(results_root, args.subjects[0])
        logger.info(f"Loaded {len(condition_labels)} condition labels: {condition_labels}")

        selectivity_metric_keys = [
            'simple_selectivity',
            'contrast_index',
            'separability',
            'distinctiveness',
        ]

        metric_ylabel_map = {
             'simple_selectivity': 'Simple Selectivity (W - Mean B)',
             'contrast_index': 'Contrast Index ((W-B)/(W+B))',
             'separability': 'Separability ((W-B)/(1-B))',
             'distinctiveness': 'Distinctiveness ((W-B)/W)',
             'within_corrs': f'Within-Metric (Reliability{ " / Inv Dist" if "euclidean_distance" in filename_suffix else "" })',
             'mean_between_corrs': f'Mean Between-Metric{ " / Inv Dist" if "euclidean_distance" in filename_suffix else "" }',
        }

        for metric_key in selectivity_metric_keys:
            logger.info(f"--- Processing metric: {metric_key} ---")
            try:
                all_subject_data = load_all_subject_data(
                    results_root, args.subjects, metric_key, filename_suffix, condition_labels
                )
                logger.info(f"Successfully loaded data for {len(all_subject_data['Subject'].unique())} subjects for metric key '{metric_key}'.")

                plot_filename_base = f"aggregated_{metric_key}_{filename_suffix}"
                if args.plot_suffix: plot_filename_base += f"_{args.plot_suffix}"
                plot_ylabel = metric_ylabel_map.get(metric_key, metric_key.replace('_', ' ').title())

                # Generate the single plot (standardCI style with counts)
                plot_filename_output = f"{plot_filename_base}.{args.save_format}"
                logger.info(f"Generating plot: {plot_filename_output}")
                plot_aggregated_metric(
                    all_subject_data, metric_key, output_dir, plot_filename_output,
                    plot_ylabel,
                    subjects=args.subjects,
                    alpha_level=args.alpha
                )

            except FileNotFoundError:
                 logger.error(f"Data file not found for metric key '{metric_key}' with suffix '{filename_suffix}'. Skipping this metric.")
                 continue
            except ValueError as e:
                 logger.error(f"Error loading data for metric key '{metric_key}': {e}. Skipping this metric.")
                 continue
            except Exception as e:
                 logger.error(f"An unexpected error occurred while processing metric key '{metric_key}': {e}", exc_info=True)
                 continue

    except FileNotFoundError as e:
        logger.error(f"File Not Found Error during setup: {e}. Please check paths and parameters.")
    except Exception as e:
        logger.error(f"An unexpected error occurred during setup: {e}", exc_info=True)


if __name__ == "__main__":
    main() 

